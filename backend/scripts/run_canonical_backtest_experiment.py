#!/usr/bin/env python3
"""Run one formal Champion/Challenger experiment and emit canonical evidence."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys
from typing import Any
from uuid import uuid4


BACKEND_ROOT = Path(__file__).resolve().parents[1]
if str(BACKEND_ROOT) not in sys.path:
    sys.path.insert(0, str(BACKEND_ROOT))

from dotenv import load_dotenv  # noqa: E402

load_dotenv(BACKEND_ROOT / ".env")

from app.db.session import SessionLocal  # noqa: E402
from app.engine.backtest import BacktestRequest, DateRange, ExecutionPolicy  # noqa: E402
from app.engine.production_policy import DEFAULT_PRODUCTION_SELECTION_POLICY  # noqa: E402
from app.services.backtest.canonical_experiment import (  # noqa: E402
    CanonicalBacktestExperiment,
    CanonicalExperimentSpec,
)
from app.services.backtest.policy_experiment import (  # noqa: E402
    CanonicalPolicyExperimentSpec,
    ScoredCandidateSnapshot,
)
from app.services.backtest.candidate_snapshot_builder import (  # noqa: E402
    ProductionRuleReplayCandidateBuilder,
)
from app.services.backtest.research_repository import ResearchBacktestRepository  # noqa: E402
from app.services.backtest.research_runner import ResearchBacktestRunner  # noqa: E402
from app.services.backtest.stock_metadata import StockMetadataHistoryProvider  # noqa: E402


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Run a same-snapshot canonical Champion/Challenger backtest experiment."
    )
    parser.add_argument(
        "--experiment-kind",
        choices=("strategy", "production-policy"),
        default="strategy",
    )
    parser.add_argument("--start", help="First signal date (YYYY-MM-DD).")
    parser.add_argument("--end", help="Last signal date (YYYY-MM-DD).")
    parser.add_argument("--strategy-id")
    parser.add_argument("--champion-params", help="Champion parameter_set JSON object.")
    parser.add_argument("--challenger-params", help="Challenger parameter_set JSON object.")
    parser.add_argument(
        "--execution-policy",
        default="{}",
        help="ExecutionPolicy JSON overrides; omitted fields use domain defaults.",
    )
    parser.add_argument("--hypothesis", required=True)
    parser.add_argument("--experiment-id")
    parser.add_argument("--target-code", action="append", default=[])
    parser.add_argument("--champion-policy-id", default="production-selection")
    parser.add_argument(
        "--challenger-policy-patch",
        help='Exactly one rule patch JSON object, e.g. {"structural_strong_hard_veto":false}.',
    )
    parser.add_argument(
        "--candidate-source",
        choices=("production-rule-replay",),
        default="production-rule-replay",
    )
    parser.add_argument(
        "--candidate-snapshot-file",
        help="Frozen ScoredCandidateSnapshot JSON generated by rule-only production replay.",
    )
    parser.add_argument(
        "--candidate-snapshot-output",
        help="Optional path to write the generated immutable candidate snapshot.",
    )
    parser.add_argument(
        "--holdout-fingerprint",
        help="Untouched holdout fingerprint; required for formal production-policy evidence.",
    )
    parser.add_argument(
        "--point-in-time-metadata",
        action="store_true",
        help="Resolve industry/is_st/name as-of each signal_date from stock_metadata_history "
        "(survivorship-bias-free). Default keeps current-static stocks metadata.",
    )
    parser.add_argument(
        "--historical-replay",
        action="store_true",
        help="Build universe from the historical pool (daily_kbars+daily_basic+point-in-time "
        "metadata) instead of the stock_quotes realtime pool. Required for holdout windows "
        "older than the realtime pool's ~56 day coverage. Implies point-in-time metadata.",
    )
    parser.add_argument("--score-line", type=float, default=72.0)
    parser.add_argument("--output-count", type=int, default=6)
    return parser


def _json_object(raw: str, field: str) -> dict[str, Any]:
    try:
        value = json.loads(raw)
    except json.JSONDecodeError as exc:
        raise ValueError(f"{field} must be valid JSON") from exc
    if not isinstance(value, dict):
        raise ValueError(f"{field} must be a JSON object")
    return value


def _required_arg(args: argparse.Namespace, name: str) -> str:
    value = getattr(args, name)
    if value is None or not str(value).strip():
        raise ValueError(f"--{name.replace('_', '-')} is required for {args.experiment_kind}")
    return str(value)


def build_spec(
    args: argparse.Namespace,
    db: Any | None = None,
) -> CanonicalExperimentSpec | CanonicalPolicyExperimentSpec:
    execution_policy = ExecutionPolicy(
        **_json_object(str(args.execution_policy), "execution_policy")
    )
    experiment_id = str(args.experiment_id or f"btexp_{uuid4().hex}")
    if args.experiment_kind == "production-policy":
        if str(args.champion_policy_id) != DEFAULT_PRODUCTION_SELECTION_POLICY.policy_id:
            raise ValueError("unknown --champion-policy-id")
        patch = _json_object(
            _required_arg(args, "challenger_policy_patch"),
            "challenger_policy_patch",
        )
        if len(patch) != 1:
            raise ValueError("challenger_policy_patch must change exactly one rule_id")
        changed_rule_id, value = next(iter(patch.items()))
        if args.candidate_snapshot_file:
            snapshot_path = Path(str(args.candidate_snapshot_file))
            payload = json.loads(snapshot_path.read_text(encoding="utf-8"))
            snapshot = ScoredCandidateSnapshot.from_payload(payload)
        else:
            if db is None:
                raise ValueError(
                    "database session is required to build a production-rule-replay snapshot"
                )
            metadata_provider = None
            historical = getattr(args, "historical_replay", False)
            if historical or getattr(args, "point_in_time_metadata", False):
                metadata_provider = StockMetadataHistoryProvider(db)
            snapshot = ProductionRuleReplayCandidateBuilder(
                db,
                stock_metadata_provider=metadata_provider,
                historical_replay=historical,
            ).build(
                start_date=_required_arg(args, "start"),
                end_date=_required_arg(args, "end"),
                execution_policy=execution_policy,
                score_line=float(args.score_line),
                output_count=int(args.output_count),
                skill_ids=None,
            )
            if args.candidate_snapshot_output:
                output = Path(str(args.candidate_snapshot_output))
                output.parent.mkdir(parents=True, exist_ok=True)
                output.write_text(
                    json.dumps(
                        snapshot.canonical_payload(),
                        ensure_ascii=False,
                        sort_keys=True,
                        allow_nan=False,
                    ),
                    encoding="utf-8",
                )
        if snapshot.source != str(args.candidate_source):
            raise ValueError("candidate snapshot source does not match --candidate-source")
        return CanonicalPolicyExperimentSpec(
            experiment_id=experiment_id,
            hypothesis=str(args.hypothesis),
            candidate_snapshot=snapshot,
            champion_policy=DEFAULT_PRODUCTION_SELECTION_POLICY,
            challenger_policy=DEFAULT_PRODUCTION_SELECTION_POLICY.with_rule_patch(
                str(changed_rule_id), value
            ),
            changed_rule_id=str(changed_rule_id),
            score_line=float(args.score_line),
            output_count=int(args.output_count),
            execution_policy=execution_policy,
            holdout_fingerprint=args.holdout_fingerprint,
            holdout_scope="untouched_holdout",
        )

    start = _required_arg(args, "start")
    end = _required_arg(args, "end")
    selector = DateRange(str(args.start), str(args.end))
    common = {
        "strategy_id": _required_arg(args, "strategy_id"),
        "date_selector": selector,
        "execution_policy": execution_policy,
        "target_codes": tuple(args.target_code),
    }
    return CanonicalExperimentSpec(
        experiment_id=experiment_id,
        hypothesis=str(args.hypothesis),
        champion=BacktestRequest(
            **common,
            parameter_set=_json_object(_required_arg(args, "champion_params"), "champion_params"),
        ),
        challenger=BacktestRequest(
            **common,
            parameter_set=_json_object(_required_arg(args, "challenger_params"), "challenger_params"),
        ),
    )


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    session = SessionLocal()
    try:
        repository = ResearchBacktestRepository(session)
        artifact = CanonicalBacktestExperiment(
            repository,
            ResearchBacktestRunner(repository),
        ).run(build_spec(args, session))
        print(json.dumps(artifact, ensure_ascii=False, sort_keys=True, allow_nan=False))
        return 2 if artifact["status"] == "failed" else 0
    except Exception as exc:  # CLI boundary: stable JSON on stderr for automation.
        session.rollback()
        print(
            json.dumps(
                {
                    "status": "failed",
                    "error": {
                        "code": str(getattr(exc, "code", "canonical_experiment_failed")),
                        "message": str(exc),
                    },
                },
                ensure_ascii=False,
                sort_keys=True,
            ),
            file=sys.stderr,
        )
        return 1
    finally:
        session.close()


if __name__ == "__main__":
    raise SystemExit(main())
